  Future<void> _importText() async {
    if (_messageController.text.isEmpty) {
      _showErrorDialog('Missing Information', 'Please paste some text first.');
      return;
    }
    if (_selectedAgencyId == null) {
      _showErrorDialog('Agency Required', 'Please select an agency from the dropdown before importing.');
      return;
    }

    setState(() {
      _isLoading = true;
    });
    
    // Show Loading Dialog
    LoadingDialog.show(context, message: 'Parsing flight data...\nPlease wait.');

    try {
      final geminiService = ref.read(geminiServiceProvider);
      final parsedData = await geminiService.parseFlightData(
        _messageController.text,
        agencyName: _selectedAgencyName,
      );
      
      if (parsedData.isEmpty) {
        throw Exception("No flights were found in the text.");
      }

      final flightsToPreview = parsedData.map((data) {
        final dateStr = data['date']?.toString() ?? '';
        DateTime? parsed;
        try {
          const months = {
            'JAN': 1, 'FEB': 2, 'MAR': 3, 'APR': 4, 'MAY': 5, 'JUN': 6,
            'JUL': 7, 'AUG': 8, 'SEP': 9, 'OCT': 10, 'NOV': 11, 'DEC': 12
          };
          final parts = dateStr.trim().split(' ');
          if (parts.length >= 2) {
            final day = int.parse(parts[0]);
            final month = months[parts[1].toUpperCase()] ?? 1;
            parsed = DateTime(DateTime.now().year, month, day);
          }
        } catch (_) {}

        return Flight(
          id: '', // Will be generated by Firestore
          agencyId: _selectedAgencyId!,
          agencyName: _selectedAgencyName ?? 'Selected Agency',
          source: data['source'] ?? '',
          destination: data['destination'] ?? '',
          date: dateStr,
          airline: data['airline'] ?? '',
          flightNumber: data['flightNumber'] ?? '',
          timing: data['timing'] ?? '',
          baggage: data['baggage'] ?? '',
          seats: data['seats'] ?? '',
          marketedPrice: (data['marketedPrice'] ?? 0).toDouble(),
          parsedDate: parsed,
          createdAt: DateTime.now(),
          via: data['via'] ?? '',
        );
      }).toList();

      if (mounted) {
        LoadingDialog.hide(context);
        String agencyName = _selectedAgencyName ?? 'Selected Agency';
        _showPreviewDialog(flightsToPreview, agencyName);
      }
    } catch (e, stackTrace) {
      if (mounted) LoadingDialog.hide(context);
      AppLogger.error('Failed to parse or save AI response', e, stackTrace);
      if (mounted) {
        _showErrorDialog('Parsing Error', e.toString());
      }
    } finally {
      if (mounted) {
        setState(() {
          _isLoading = false;
        });
      }
    }
  }

