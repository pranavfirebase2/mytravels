              },
              child: const Text('Confirm & Upload'),
            ),
          ],
        );
      },
    );
  }

  Future<void> _uploadToFirebase(List<Flight> flights) async {
    setState(() {
      _isLoading = true;
    });
    final progressNotifier = ValueNotifier<String>('Uploading 0/${flights.length} flights...\nPlease wait.');
    LoadingDialog.show(context, messageNotifier: progressNotifier);
    try {
      final repository = ref.read(flightRepositoryProvider);
      await repository.saveFlights(flights, onProgress: (count, total) {
        progressNotifier.value = 'Uploading $count/$total flights...\nPlease wait.';
      });
      
      if (mounted) {
        LoadingDialog.hide(context);
        ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text('Successfully imported ${flights.length} flights!'), backgroundColor: AppColors.successGreen));
        _messageController.clear();
      }
    } catch (e, stackTrace) {
      if (mounted) LoadingDialog.hide(context);
      AppLogger.error('Upload failed', e, stackTrace);
      if (mounted) {
        _showErrorDialog('Upload Error', e.toString());
      }
    } finally {
      if (mounted) {
        setState(() {
          _isLoading = false;
        });
      }
    }
  }

