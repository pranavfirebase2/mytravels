import 'package:flutter/material.dart';
import '../../../../core/constants/app_colors.dart';
import 'package:go_router/go_router.dart';
import '../../../../core/widgets/app_layout.dart';
import '../../../../core/widgets/loading_dialog.dart';
import '../../../../core/providers/core_providers.dart';
import '../../../../core/utils/logger.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import '../../../flights/presentation/providers/flight_providers.dart';
import '../../../flights/domain/entities/flight.dart';
import '../../../agency/presentation/providers/agency_providers.dart';

class ImportPage extends ConsumerStatefulWidget {
  const ImportPage({super.key});

  @override
  ConsumerState<ImportPage> createState() => _ImportPageState();
}

class _ImportPageState extends ConsumerState<ImportPage> {
  final TextEditingController _messageController = TextEditingController();
  final TextEditingController _timeController = TextEditingController();
  String? _selectedAgencyId;
  String? _selectedAgencyName;


  @override
  void dispose() {
    _messageController.dispose();
    _timeController.dispose();
    super.dispose();
  }

  bool _isLoading = false;

  void _showErrorDialog(String title, String message) {
    showDialog(
      context: context,
      builder: (context) => AlertDialog(
        title: Text(title, style: const TextStyle(color: AppColors.errorRed)),
        content: Text(message),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context),
            child: const Text('OK'),
          ),
        ],
      ),
    );
  }

  Future<void> _importText() async {
    if (_messageController.text.isEmpty) {
      _showErrorDialog('Missing Information', 'Please paste some text first.');
      return;
    }
    if (_selectedAgencyId == null) {
      _showErrorDialog('Agency Required', 'Please select an agency from the dropdown before importing.');
      return;
    }

    setState(() {
      _isLoading = true;
    });
    
    // Show Loading Dialog
    LoadingDialog.show(context, message: 'Parsing flight data...\nPlease wait.');

    try {
      final geminiService = ref.read(geminiServiceProvider);
      final parsedData = await geminiService.parseFlightData(_messageController.text);
      
      if (parsedData.isEmpty) {
        throw Exception("No flights were found in the text.");
      }

      final flightsToPreview = parsedData.map((data) {
        final dateStr = data['date']?.toString() ?? '';
        DateTime? parsed;
        try {
          const months = {
            'JAN': 1, 'FEB': 2, 'MAR': 3, 'APR': 4, 'MAY': 5, 'JUN': 6,
            'JUL': 7, 'AUG': 8, 'SEP': 9, 'OCT': 10, 'NOV': 11, 'DEC': 12
          };
          final parts = dateStr.trim().split(' ');
          if (parts.length >= 2) {
            final day = int.parse(parts[0]);
            final month = months[parts[1].toUpperCase()] ?? 1;
            parsed = DateTime(DateTime.now().year, month, day);
          }
        } catch (_) {}

        return Flight(
          id: '', // Will be generated by Firestore
          agencyId: _selectedAgencyId!,
          agencyName: _selectedAgencyName ?? 'Selected Agency',
          source: data['source'] ?? '',
          destination: data['destination'] ?? '',
          date: dateStr,
          airline: data['airline'] ?? '',
          flightNumber: data['flightNumber'] ?? '',
          timing: data['timing'] ?? '',
          baggage: data['baggage'] ?? '',
          seats: data['seats'] ?? '',
          marketedPrice: (data['marketedPrice'] ?? 0).toDouble(),
          parsedDate: parsed,
          createdAt: DateTime.now(),
        );
      }).toList();

      if (mounted) {
        LoadingDialog.hide(context);
        String agencyName = _selectedAgencyName ?? 'Selected Agency';
        _showPreviewDialog(flightsToPreview, agencyName);
      }
    } catch (e, stackTrace) {
      if (mounted) LoadingDialog.hide(context);
      AppLogger.error('Failed to parse or save AI response', e, stackTrace);
      if (mounted) {
        _showErrorDialog('Parsing Error', e.toString());
      }
    } finally {
      if (mounted) {
        setState(() {
          _isLoading = false;
        });
      }
    }
  }

  void _showPreviewDialog(List<Flight> flights, String agencyName) {
    showDialog(
      context: context,
      barrierDismissible: false,
      builder: (context) {
        return AlertDialog(
          title: Text('Preview Data (${flights.length} Flights for $agencyName)'),
          content: SizedBox(
            width: double.maxFinite,
            child: ListView.separated(
              shrinkWrap: true,
              itemCount: flights.length,
              separatorBuilder: (context, index) => const Divider(),
              itemBuilder: (context, index) {
                final f = flights[index];
                return ListTile(
                  leading: const Icon(Icons.flight, color: AppColors.iconBlue),
                  title: Text('${f.source} → ${f.destination}  |  ${f.date}', style: const TextStyle(fontWeight: FontWeight.bold)),
                  subtitle: Text('Airline: ${f.airline} | Price: ₹${f.marketedPrice} | Baggage: ${f.baggage}\nFlight No: ${f.flightNumber} | Timing: ${f.timing}\nAgency: $agencyName'),
                  isThreeLine: true,
                );
              },
            ),
          ),
          actions: [
            TextButton(
              onPressed: () => Navigator.pop(context), // Close without saving
              child: const Text('Cancel', style: TextStyle(color: AppColors.errorRed)),
            ),
            ElevatedButton(
              style: ElevatedButton.styleFrom(backgroundColor: AppColors.primaryBlue, foregroundColor: AppColors.white),
              onPressed: () {
                Navigator.pop(context); // Close dialog
                _uploadToFirebase(flights); // Start upload
              },
              child: const Text('Confirm & Upload'),
            ),
          ],
        );
      },
    );
  }

  Future<void> _uploadToFirebase(List<Flight> flights) async {
    setState(() {
      _isLoading = true;
    });
    final progressNotifier = ValueNotifier<String>('Uploading 0/${flights.length} flights...\nPlease wait.');
    LoadingDialog.show(context, messageNotifier: progressNotifier);
    try {
      final repository = ref.read(flightRepositoryProvider);
      await repository.saveFlights(flights, onProgress: (count, total) {
        progressNotifier.value = 'Uploading $count/$total flights...\nPlease wait.';
      });
      
      if (mounted) {
        LoadingDialog.hide(context);
        ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text('Successfully imported ${flights.length} flights!'), backgroundColor: AppColors.successGreen));
        _messageController.clear();
      }
    } catch (e, stackTrace) {
      if (mounted) LoadingDialog.hide(context);
      AppLogger.error('Upload failed', e, stackTrace);
      if (mounted) {
        _showErrorDialog('Upload Error', e.toString());
      }
    } finally {
      if (mounted) {
        setState(() {
          _isLoading = false;
        });
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    return AppLayout(
      activeRoute: '/import',
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          _buildHeaderCard(),
          const SizedBox(height: 16),
          _buildImportCard(),
          const SizedBox(height: 16),
          _buildFooterCard(context),
        ],
      ),
    );
  }

  Widget _buildHeaderCard() {
    return Card(
      color: AppColors.cardBackground,
      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(8)),
      child: Padding(
        padding: const EdgeInsets.all(16.0),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: const [
            Text('Import Market Fare Data', style: TextStyle(fontSize: 18, fontWeight: FontWeight.bold)),
            SizedBox(height: 4),
            Text('Select the agency from Agency Master. The same master name is used for starring and comparison deductions. Updated Time is optional.', style: TextStyle(color: AppColors.textGrey)),
          ],
        ),
      ),
    );
  }

  Widget _buildImportCard() {
    return Card(
      color: AppColors.cardBackground,
      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(8)),
      child: Padding(
        padding: const EdgeInsets.all(24.0),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            TextField(
              controller: _messageController,
              maxLines: 10,
              decoration: const InputDecoration(
                hintText: 'Paste WhatsApp marketing text here...',
                border: OutlineInputBorder(),
              ),
            ),
            const SizedBox(height: 16),
            ref.watch(agenciesStreamProvider).when(
              loading: () => const Center(child: CircularProgressIndicator()),
              error: (e, st) => Text('Error: $e'),
              data: (agencies) {
                return Row(
                  children: [
                    Expanded(
                      flex: 2,
                      child: DropdownButtonFormField<String>(
                        value: _selectedAgencyId,
                        decoration: const InputDecoration(
                          border: OutlineInputBorder(),
                          contentPadding: EdgeInsets.symmetric(horizontal: 12, vertical: 8),
                        ),
                        hint: const Text('Select Agency / Group'),
                        items: agencies.map((agency) {
                          return DropdownMenuItem(
                            value: agency.id,
                            child: Text(agency.name),
                          );
                        }).toList(),
                        onChanged: (val) {
                          setState(() {
                            _selectedAgencyId = val;
                            if (val != null) {
                              _selectedAgencyName = agencies.firstWhere((a) => a.id == val).name;
                            }
                          });
                        },
                      ),
                    ),
                    const SizedBox(width: 16),
                    Expanded(
                      flex: 1,
                      child: TextField(
                        controller: _timeController,
                        decoration: const InputDecoration(
                          hintText: 'Updated time (optional)',
                          border: OutlineInputBorder(),
                          contentPadding: EdgeInsets.symmetric(horizontal: 12, vertical: 8),
                        ),
                      ),
                    ),
                    const SizedBox(width: 16),
                    ElevatedButton(
                      style: ElevatedButton.styleFrom(
                        backgroundColor: AppColors.primaryBlue,
                        foregroundColor: AppColors.white,
                        padding: const EdgeInsets.symmetric(horizontal: 24, vertical: 16),
                      ),
                      onPressed: _isLoading ? null : _importText,
                      child: _isLoading 
                        ? const SizedBox(height: 20, width: 20, child: CircularProgressIndicator(color: AppColors.white, strokeWidth: 2))
                        : const Text('Import Pasted Text'),
                    ),
                  ],
                );
              }
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildFooterCard(BuildContext context) {
    return Card(
      color: AppColors.cardBackground,
      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(8)),
      child: Padding(
        padding: const EdgeInsets.all(16.0),
        child: Row(
          mainAxisAlignment: MainAxisAlignment.spaceBetween,
          children: [
            TextButton(
              onPressed: () {
                context.go('/agency');
              },
              child: const Text(
                'Open Agency Master → Add agencies, edit deductions or star agencies',
                style: TextStyle(color: AppColors.linkPurple, decoration: TextDecoration.underline),
              ),
            ),
            ElevatedButton(
              style: ElevatedButton.styleFrom(
                backgroundColor: AppColors.buttonGrey,
                foregroundColor: AppColors.white,
              ),
              onPressed: () {
                // Clear daily data action
              },
              child: const Text('Clear Daily Data'),
            )
          ],
        ),
      ),
    );
  }
}
